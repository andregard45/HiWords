# Intentionally localized data (matched against user content); kept but translated
# comments near them explain why they stay.
KEEP = {" · ", "备注", "我的备注", "已掌握", "未知", "释义"}

def main():
    keys = json.load(open('/workspace/.comments.json', encoding='utf-8'))
    extra = []
    if len(sys.argv) > 1:
        ex = json.load(open(sys.argv[1], encoding='utf-8'))
        extra = list(ex) if isinstance(ex, dict) else ex
    mapping, missing = {}, []
    for k in keys + extra:
        if k in DICT:
            mapping[k] = DICT[k]
        elif k in STR:
            mapping[k] = STR[k]
        elif k in KEEP:
            continue
        else:
            missing.append(k)
    json.dump(mapping, open('/workspace/.tools/map.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
    print(f'mapped={len(mapping)} missing={len(missing)}')
    for m in missing:
        print('MISS:', repr(m))

main()
